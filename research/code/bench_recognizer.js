/* Two hands: the second hand is moved so the touching fingertips meet, as in the real signs. */
function touch(a, b, ia, ib, gap) {
  var dx = a.lm[ia].x - b.lm[ib].x + gap, dy = a.lm[ia].y - b.lm[ib].y;
  b.lm = b.lm.map(function (p) { return { x: p.x + dx, y: p.y + dy, z: p.z }; });
  return [a, b];
}
