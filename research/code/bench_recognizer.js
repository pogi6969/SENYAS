/* One frame: shape, facing, wrist position (image units), extra rotation, noise level. */
function jitterPose(shape, amt) {
  var r = Hand.resolve(shape);
  return { fl: r.fl.map(function (c) { return c.map(function (a) { return Math.max(0, a + gauss() * 7 * amt); }); }), sp: r.sp.map(function (a) { return a + gauss() * 3 * amt; }), tt: V.add(r.tt, [gauss() * 0.03 * amt, gauss() * 0.03 * amt, gauss() * 0.03 * amt]) };
}
function rot(f, ax, ay, az) {
  function rx(v) { var c = Math.cos(ax), s = Math.sin(ax); return [v[0], v[1] * c - v[2] * s, v[1] * s + v[2] * c]; }
  function ry(v) { var c = Math.cos(ay), s = Math.sin(ay); return [v[0] * c + v[2] * s, v[1], -v[0] * s + v[2] * c]; }
  function rz(v) { var c = Math.cos(az), s = Math.sin(az); return [v[0] * c - v[1] * s, v[0] * s + v[1] * c, v[2]]; }
  return f.map(function (v) { return rz(rx(ry(v))); });
}
function frameOf(pose, fm, pos, noise, left) {
  var pts = Hand.orient(Hand.local(pose), fm).slice(0, 21);
  if (left) pts = Hand.mirror(pts);
  var k = 0.16, aspect = 4 / 3, m = 0.085;
  var world = pts.map(function (p) { return { x: p[0] * m + gauss() * 0.0025 * noise, y: -p[1] * m + gauss() * 0.0025 * noise, z: -p[2] * m + gauss() * 0.0035 * noise }; });
  var img = pts.map(function (p) { return { x: (pos[0] + p[0] * k) / aspect + gauss() * 0.0015 * noise, y: pos[1] - p[1] * k + gauss() * 0.0015 * noise, z: 0 }; });
  return { lm: img, wl: world, label: left ? "Right" : "Left" };
}
function result(hands) {
  return { landmarks: hands.map(function (h) { return h.lm; }), worldLandmarks: hands.map(function (h) { return h.wl; }), handednesses: hands.map(function (h) { return [{ categoryName: h.label }]; }) };
}

/* ---------- 1. static handshapes, single frames ---------- */
function staticTest(level) {
  var ok = 0, n = 0, conf = {};
  LETTERS.forEach(function (L) {
    for (var t = 0; t < 40; t++) {
      var fm = rot(Hand.frame(ORI[L] || (t % 2 ? "Fa" : "F")), gauss() * 0.22 * level, gauss() * 0.3 * level, gauss() * 0.2 * level);
      var fr = frameOf(jitterPose(L, level), fm, [0.66, 0.6], level, t % 4 === 3);
      var hs = Recog.hands(result([fr]), 4 / 3, false), h = hs[0];
      var b = Recog.pick(Recog.nearest(h.f, [], h.f2), Recog.allowFor("abc"));
      n++; var got = b ? b.tok.slice(2) : "-";
      if (got === L) ok++; else { conf[L] = conf[L] || {}; conf[L][got] = (conf[L][got] || 0) + 1; }
    }
  });
  return { level: level, n: n, accuracy: ok / n, confusions: conf };
}

/* ---------- 2. sessions: sequences through the live decision rules ---------- */
function run(mode, frames) {
  var got = [];
  var s = new Recog.Session({ commit: function (d) { got.push(d.tok); } });
  s.mode = mode; s.hold = 400;
  frames.forEach(function (fr, i) { s.frame(result(fr), i * 33.3, 4 / 3); });
  return got;
}
